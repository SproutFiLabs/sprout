/** Environment for a local server that should batch reads through Multicall3. */
export const LOCAL_MULTICALL_ENV = { SPROUT_MULTICALL3_ADDRESS: CANONICAL_MULTICALL3 } as const;

/** Place Multicall3 at its canonical address on a local Anvil node. */
export async function installMulticall3(publicClient: PublicClient): Promise<void> {
  await publicClient.request({
    method: 'anvil_setCode',
    params: [CANONICAL_MULTICALL3, MULTICALL3_RUNTIME],
  } as never);
  const installed = await publicClient.getCode({ address: CANONICAL_MULTICALL3 });
  if (!installed || keccak256(installed) !== MULTICALL3_CODEHASH) {
    throw new Error('Multicall3 was not installed on the local node');
  }
}
